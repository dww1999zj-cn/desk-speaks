-- desk_reports 数据清理脚本
-- 在 Supabase Dashboard → SQL Editor 中执行
-- 建议：先跑「0. 查看现状」，再取消注释其中一种清理方式

-- ---------------------------------------------------------------------------
-- 0. 查看现状（建议先执行）
-- ---------------------------------------------------------------------------
SELECT
  COUNT(*) AS total_rows,
  MIN(created_at) AS oldest,
  MAX(created_at) AS newest
FROM desk_reports;

SELECT created_at::date AS day, COUNT(*) AS rows
FROM desk_reports
GROUP BY 1
ORDER BY 1 DESC
LIMIT 30;

